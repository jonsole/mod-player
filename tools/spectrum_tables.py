#!/usr/bin/env python3
"""Generates the spectrum analyser's tables (issue #24, ADR-0014).

Generated once and committed, so the C model (host/spectrum.c) and the
Verilog (hw/rtl/spectrum.v) read the same integers and no floating point
is involved in a build.

  window   1024-point periodic Hann window, Q15 (0..32767)
  sine     sin(2 pi i / 1024) for i = 0..256, Q17 (0..131071): a quarter
           wave, from which the FFT's twiddle factors are read
  bars     for each of the 48 bars, the first and last FFT bin it covers:
           log-spaced from 50 Hz to 20 kHz at 48 kHz / 1024 = 46.875 Hz a
           bin (low bars share a bin, as the bins are wider than the bands)

Usage: spectrum_tables.py <out.h> <window.hex> <sine.hex> <bars.hex>
"""
import math
import sys

N = 1024
FS = 48000
BARS = 48
F_LO, F_HI = 50.0, 20000.0
WINDOW_ONE = 32767        # Q15
SINE_ONE = 131071         # Q17, 18-bit signed


def window():
    return [round(WINDOW_ONE * 0.5 * (1 - math.cos(2 * math.pi * n / N))) for n in range(N)]


def sine():
    return [round(SINE_ONE * math.sin(2 * math.pi * i / N)) for i in range(N // 4 + 1)]


def bars():
    bin_hz = FS / N
    edges = [F_LO * (F_HI / F_LO) ** (k / BARS) for k in range(BARS + 1)]
    out, last = [], 0
    for b in range(BARS):
        lo = max(last + 1, round(edges[b] / bin_hz))       # every bar its own bins
        hi = max(lo, round(edges[b + 1] / bin_hz) - 1)
        out.append((lo, hi))
        last = hi
    return out


def main(argv):
    w, s, b = window(), sine(), bars()
    with open(argv[1], "w", newline="\n") as f:
        f.write("/* Generated by tools/spectrum_tables.py: the spectrum analyser's tables\n"
                " * (ADR-0014). Do not edit. */\n#ifndef SPECTRUM_TABLES_H\n#define SPECTRUM_TABLES_H\n#include <stdint.h>\n\n")
        f.write("#define SPECTRUM_N %d\n#define SPECTRUM_BARS %d\n\n" % (N, BARS))
        f.write("static const uint16_t spectrum_window[%d] = {\n" % N)
        for i in range(0, N, 12):
            f.write("    " + ", ".join(str(v) for v in w[i:i + 12]) + ",\n")
        f.write("};\n\nstatic const int32_t spectrum_sine[%d] = {\n" % len(s))
        for i in range(0, len(s), 10):
            f.write("    " + ", ".join(str(v) for v in s[i:i + 10]) + ",\n")
        f.write("};\n\n/* first and last FFT bin of each bar */\nstatic const uint16_t spectrum_bar_lo[%d] = {%s};\n"
                % (BARS, ", ".join(str(lo) for lo, _ in b)))
        f.write("static const uint16_t spectrum_bar_hi[%d] = {%s};\n\n#endif\n"
                % (BARS, ", ".join(str(hi) for _, hi in b)))
    with open(argv[2], "w", newline="\n") as f:
        f.write("\n".join("%04x" % v for v in w) + "\n")
    with open(argv[3], "w", newline="\n") as f:
        f.write("\n".join("%05x" % v for v in s) + "\n")
    with open(argv[4], "w", newline="\n") as f:                 # lo << 10 | hi
        f.write("\n".join("%05x" % (lo << 10 | hi) for lo, hi in b) + "\n")


if __name__ == "__main__":
    main(sys.argv)
