#!/usr/bin/env python3
"""Generates the HDMI Resampler's FIR coefficients (ADR-0010).

The table is generated once and committed, so the C model and the Verilog
read the same integers and no floating point is involved in a build.

Prototype: a Kaiser-windowed sinc, causal over [0, TAPS) intermediate
samples, sampled at PHASES points per sample: h[n] for n = 0..TAPS*PHASES.
It is symmetric, h[n] = h[TAPS*PHASES - n], and h[0] = h[TAPS*PHASES] = 0, so
only h[1..TAPS*PHASES/2] is stored (2048 entries, two block RAMs).

Usage: resampler_coefs.py <out.h> <out.hex>
"""
import math
import sys

CCK_HZ = 3546895          # Paula's frame rate
CIC_R = 16                # first stage decimation
FS1 = CCK_HZ / CIC_R      # intermediate rate, 221681 Hz
TAPS = 128                # FIR taps per output
PHASES = 32               # coefficient table points per intermediate sample
CUTOFF_HZ = 24000         # -6 dB point: passband to 20 kHz, stopband from 28 kHz
BETA = 7.2                # Kaiser window shape: about 74 dB stopband
DC_GAIN = 1 << 18         # sum of the TAPS coefficients of any phase
COEF_BITS = 18

N = TAPS * PHASES
HALF = N // 2


def bessel_i0(x):
    total, term, k = 1.0, 1.0, 1
    while term > 1e-20 * total:
        term *= (x / (2 * k)) ** 2
        total += term
        k += 1
    return total


def prototype():
    centre = N / 2
    fc = CUTOFF_HZ / FS1               # cycles per intermediate sample
    h = []
    for n in range(N + 1):
        t = (n - centre) / PHASES      # in intermediate samples
        s = 2 * fc if t == 0 else math.sin(2 * math.pi * fc * t) / (math.pi * t)
        r = (n - centre) / centre
        w = bessel_i0(BETA * math.sqrt(max(0.0, 1 - r * r))) / bessel_i0(BETA)
        h.append(s * w)
    h[0] = h[N] = 0.0
    scale = DC_GAIN * PHASES / sum(h)  # each phase sums to about DC_GAIN
    h = [round(v * scale) for v in h]
    # Make each phase sum to exactly DC_GAIN by nudging its tap nearest the
    # centre (with its mirror image), so DC gain doesn't depend on phase.
    # Phase 16's centre taps are a mirrored pair, so it can be left 1 off.
    for i in range(PHASES // 2 + 1):
        n = HALF - ((HALF - i) % PHASES)       # largest n <= HALF in phase i
        r = DC_GAIN - sum(h[j * PHASES + i] for j in range(TAPS))
        if i == PHASES // 2:
            r //= 2
        h[n] += r
        if n != HALF:
            h[N - n] += r
    return h


def main():
    out_h, out_hex = sys.argv[1], sys.argv[2]
    h = prototype()
    for n in range(N + 1):
        assert h[n] == h[N - n]
    half = h[1:HALF + 1]
    lim = 1 << (COEF_BITS - 1)
    assert all(-lim <= v < lim for v in half)
    # interpolation needs (h[n+1] - h[n]) in 18 bits too
    assert all(-lim <= h[n + 1] - h[n] < lim for n in range(N))
    sums = [sum(h[j * PHASES + i] for j in range(TAPS)) for i in range(PHASES)]
    with open(out_h, "w", newline="\n") as f:
        f.write("/* Generated by tools/resampler_coefs.py: do not edit. */\n")
        f.write("#ifndef RESAMPLER_COEFS_H\n#define RESAMPLER_COEFS_H\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write(f"#define RESAMPLER_TAPS {TAPS}\n#define RESAMPLER_PHASES {PHASES}\n")
        f.write(f"#define RESAMPLER_HALF {HALF}\n\n")
        f.write(f"/* h[n] for n = 1..{HALF}; phase sums {min(sums)}..{max(sums)} */\n")
        f.write(f"static const int32_t resampler_coefs[{HALF}] = {{\n")
        for k in range(0, HALF, 8):
            f.write("    " + ", ".join(f"{v}" for v in half[k:k + 8]) + ",\n")
        f.write("};\n\n#endif\n")
    with open(out_hex, "w", newline="\n") as f:
        for v in half:
            f.write(f"{v & ((1 << COEF_BITS) - 1):05x}\n")
    print(f"{HALF} coefficients, peak {max(half)}, phase sums {min(sums)}..{max(sums)}")


if __name__ == "__main__":
    main()
